import time

import numpy as np
import quimb.tensor as qtn

from qpe_toolbox import EXACT

from .quantum_phase_estimation import evolution_powers


def robust_phase_estimation(
    hamiltonian,
    psi0,
    n_repetitions,
    n_trotter_steps,
    n_shots,
    *,
    t0=1.0,
    trotter_order=1,
    cutoff=1e-10,
    max_bond=None,
    rng=None,
    verbosity=0,
):
    r"""
    Perform the Robust Phase Estimation (RPE) algorithm.

    This routine estimates the phase associated with the unitary
    time evolution generated by a Hamiltonian using a sequence of
    Hadamard tests at increasing evolution times. It is the composition of
    the measurement stage ``measure_rpe_phases`` (the raw phases
    :math:`\phi_m`) and the classical retrieval stage
    ``refine_rpe_phases`` (the refined phases :math:`\theta_m`).

    The algorithm estimates the phase :math:`\varphi = E_0 t_0` accumulated over
    the base evolution time :math:`t_0`. It refines this estimate over
    ``n_repetitions`` iterations indexed by :math:`m = 0, 1, \dots, M-1`, using
    the evolution time :math:`t_0 2^m` at iteration :math:`m` and gaining one bit
    of precision per iteration. The final estimate satisfies
    :math:`d(\theta, E_0 t_0) \leq 2^{-(M-1)}\pi/3` with :math:`M` the number of
    repetitions. Recover the energy as :math:`E_0 = \theta / t_0`.

    Parameters
    ----------
    hamiltonian : Hamiltonian
        Hamiltonian object from the ``Hamiltonian`` class.
    psi0 : :quimb-api:`MatrixProductState`
        Initial quantum state :math:`\ket{\psi_0}` of the system.
    n_repetitions : int
        Number of RPE iterations :math:`M`. Iterations are indexed by
        :math:`m = 0, 1, \dots, M-1` with evolution time :math:`t_0 2^m`, and
        each iteration adds one bit of precision. To reach a precision of order
        :math:`\varepsilon`, take :math:`M = \lceil \log_2 \varepsilon^{-1}
        \rceil`; the guaranteed bound is then :math:`2^{-(M-1)}\pi/3 \simeq
        2\varepsilon`.
    n_trotter_steps : int or qpe_toolbox.EXACT
        Number of Trotter steps for the ``m=0`` evolution; multiplied by
        ``2**m`` at each iteration to keep the Trotter step size constant.
        Use ``EXACT`` for exact time evolution.
    n_shots : int or qpe_toolbox.EXACT
        Number of measurement shots used in the Hadamard test.
        Use ``EXACT`` to compute probabilities exactly.
    t0 : float, default ``1.0``
        Base evolution time, equivalent to a rescaling of the Hamiltonian.
        The phase estimated is :math:`\varphi = E_0 t_0`. Choose :math:`t_0`
        so that :math:`|E_0 t_0| < \pi`, otherwise the :math:`m = 0` phase
        is ambiguous.
    trotter_order : int, default ``1``
        Order of the Trotter-Suzuki decomposition. Ignored when
        `n_trotter_steps is EXACT`.
    cutoff : float, default ``1e-10``
        Singular-value truncation threshold of the underlying
        :quimb-api:`CircuitMPS`.
    max_bond : int or None, default ``None``
        Maximum bond dimension of the underlying :quimb-api:`CircuitMPS`. If
        ``None``, no explicit limit is imposed.
    rng : :numpy-random:`numpy.random.Generator <generator>`, optional
        Random generator for the finite-shot sampling. Ignored when
        ``n_shots`` is ``EXACT``.
    verbosity : int, default ``0``
        Verbosity level. If >= 1, print the measured and refined phases of every
        iteration. If >= 2, also print the measured phases as they are computed.

    Returns
    -------
    theta_values : (M,) array of float
        Phase estimates :math:`\theta_0, \dots, \theta_{M-1}` of
        :math:`\varphi = E_0 t_0`, one per iteration. The last element is the
        most accurate estimate; recover the energy as :math:`\theta / t_0`.
    """
    phi_values = measure_rpe_phases(
        hamiltonian,
        psi0,
        n_repetitions,
        n_trotter_steps,
        n_shots,
        t0=t0,
        trotter_order=trotter_order,
        cutoff=cutoff,
        max_bond=max_bond,
        rng=rng,
        verbosity=verbosity,
    )
    theta_values = refine_rpe_phases(phi_values)

    if verbosity >= 1:
        print(f"m \t {'phi_m':<6} \t {'theta_m':<6}")
        for m, (phi, theta) in enumerate(zip(phi_values, theta_values, strict=True)):
            print(f"{m} \t {np.round(phi, 4): 6} \t {np.round(theta, 4): 6}")

    return theta_values


def measure_rpe_phases(
    hamiltonian,
    psi0,
    n_repetitions,
    n_trotter_steps,
    n_shots,
    *,
    t0=1.0,
    trotter_order=1,
    cutoff=1e-10,
    max_bond=None,
    rng=None,
    verbosity=0,
):
    r"""
    Measure the raw RPE phases :math:`\phi_m` for :math:`m = 0, \dots, M-1`.

    This is the measurement stage of Robust Phase Estimation, returning
    :math:`\phi_m = -\arg \bra{\psi_0} U^{2^m} \ket{\psi_0}` with
    :math:`U = e^{-iHt_0}`. Feed the result to ``refine_rpe_phases`` to obtain
    the refined phase estimates.

    Parameters
    ----------
    hamiltonian : Hamiltonian
        Hamiltonian object from the ``Hamiltonian`` class.
    psi0 : :quimb-api:`MatrixProductState`
        Initial quantum state :math:`\ket{\psi_0}` of the system.
    n_repetitions : int
        Number of RPE iterations :math:`M`.
    n_trotter_steps : int or qpe_toolbox.EXACT
        Number of Trotter steps for the ``m=0`` evolution; multiplied by
        ``2**m`` at each iteration to keep the Trotter step size constant.
        Use ``EXACT`` for exact time evolution.
    n_shots : int or qpe_toolbox.EXACT
        Number of measurement shots emulated at each iteration. Use ``EXACT``
        to return the exact phases.
    t0 : float, default ``1.0``
        Base evolution time, equivalent to a rescaling of the Hamiltonian.
        The measured phase is :math:`\phi_m = -\arg \bra{\psi_0} U^{2^m}
        \ket{\psi_0}` with :math:`U = e^{-iHt_0}`.
    trotter_order : int, default ``1``
        Order of the Trotter-Suzuki decomposition.
    cutoff : float, default ``1e-10``
        Singular-value truncation threshold of the underlying
        :quimb-api:`CircuitMPS`.
    max_bond : int or None, default ``None``
        Maximum bond dimension of the underlying :quimb-api:`CircuitMPS`. If
        ``None``, no explicit limit is imposed.
    rng : :numpy-random:`numpy.random.Generator <generator>`, optional
        Random generator for the finite-shot sampling. Ignored when
        ``n_shots`` is ``EXACT``.
    verbosity : int, default ``0``
        Verbosity level. If >= 2, print the phase measured at each iteration.

    Returns
    -------
    phi_values : (M,) array of float
        Raw phase estimates :math:`\phi_0, \dots, \phi_{M-1}` in radians.
    """
    st = time.time()
    if rng is None:
        rng = np.random.default_rng()

    unitaries = evolution_powers(
        hamiltonian, t0, n_trotter_steps, n_repetitions, trotter_order=trotter_order
    )

    phi_values = np.empty(n_repetitions)
    if verbosity >= 2:
        print(f"m \t {'phi_m':<6} \t {'time (s)'}")

    for m in range(n_repetitions):
        phi_values[m] = rpe_get_hadamard_output(
            psi0,
            unitaries[m],
            n_shots,
            cutoff=cutoff,
            max_bond=max_bond,
            rng=rng,
        )
        if verbosity >= 2:
            et = time.time() - st
            print(f"{m} \t {np.round(phi_values[m], 4): 6} \t {et:<6.1f}")

    return phi_values


def refine_rpe_phases(phi_values):
    r"""
    Refine the raw RPE phases :math:`\phi_m` into the estimates :math:`\theta_m`.

    This is the classical, simulation-free retrieval stage of Robust Phase
    Estimation. Starting from :math:`\theta_0 = \phi_0`, each :math:`\theta_m`
    is the candidate :math:`(\phi_m + 2\pi k)/2^m` nearest to the previous
    estimate :math:`\theta_{m-1}`.

    Parameters
    ----------
    phi_values : (M,) array_like of float
        Raw phase estimates :math:`\phi_0, \dots, \phi_{M-1}` in radians, as
        returned by ``measure_rpe_phases``.

    Returns
    -------
    theta_values : (M,) array of float
        Refined phase estimates :math:`\theta_0, \dots, \theta_{M-1}`. The last
        element is the most accurate estimate.
    """
    phi_values = np.asarray(phi_values)
    if phi_values.ndim != 1 or phi_values.size < 1:
        raise ValueError(f"Invalid phi_values shape: {phi_values.shape}")

    theta_values = np.empty_like(phi_values, dtype=float)
    # initialization theta_{-1} = 0, hence theta_0 = phi_0
    theta_values[0] = phi_values[0]
    for m in range(1, len(phi_values)):
        # refine the previous guess theta_{m-1}
        theta_values[m] = rpe_update_theta(phi_values[m], theta_values[m - 1], m)
    return theta_values


def rpe_get_hadamard_output(
    psi0,
    unitary,
    n_shots,
    *,
    cutoff=1e-10,
    max_bond=None,
    rng=None,
):
    r"""
    Estimate minus the phase of :math:`\bra{\psi_0} U \ket{\psi_0}` for one RPE iteration.

    The returned phase is :math:`\phi = -\arg \bra{\psi_0} U \ket{\psi_0}`,
    independent of the norm of ``psi0``. With ``EXACT`` it is exact; with finite
    ``n_shots`` the real and imaginary parts of the overlap each carry the shot
    noise of a Hadamard test. For :math:`U = e^{-iHt}` and an eigenstate
    :math:`\ket{\psi_0}` of energy :math:`E_0`, the result is :math:`E_0 t`.

    Parameters
    ----------
    psi0 : :quimb-api:`MatrixProductState`
        Initial quantum state :math:`\ket{\psi_0}`.
    unitary : :quimb-api:`Gate` or iterable of :quimb-api:`Gate`
        The unitary :math:`U`, either a single gate (e.g. an exact :math:`U`) or
        its gate decomposition as an iterable of gates (e.g. a Trotterized
        :math:`U`), acting on the data register without controls.
    n_shots : int or qpe_toolbox.EXACT
        Number of measurement shots emulated. Use ``EXACT`` to use the exact
        expectation values.
    cutoff : float, default ``1e-10``
        Singular-value truncation threshold of the underlying
        :quimb-api:`CircuitMPS`.
    max_bond : int or None, default ``None``
        Maximum bond dimension of the underlying :quimb-api:`CircuitMPS`. If
        ``None``, no explicit limit is imposed.
    rng : :numpy-random:`numpy.random.Generator <generator>`, optional
        Random generator for the finite-shot sampling. Ignored when ``n_shots``
        is ``EXACT``.

    Returns
    -------
    phi : float
        Estimated phase angle in radians.
    """
    # This is an optimization of the classical simulation, not a faithful
    # emulation of the quantum computation. On real hardware, X and Y would each
    # come from an independent Hadamard test (ancilla qubit, controlled-U, and
    # n_shots projective measurements). Here we instead compute the exact overlap
    # z = <psi|U|psi> from a single control-free simulation, then draw X and Y
    # from their exact Bernoulli distributions. This is statistically equivalent
    # (the ancilla outcome is Bernoulli with P(1) = (1 - Re/Im z) / 2) but avoids
    # the ancilla qubit and the per-shot sampling loop.
    z = _rpe_overlap(psi0, unitary, cutoff=cutoff, max_bond=max_bond)
    if n_shots is EXACT:
        X, Y = z.real, z.imag
    else:
        if rng is None:
            rng = np.random.default_rng()
        X = _sample_hadamard(z.real, n_shots, rng)
        Y = _sample_hadamard(z.imag, n_shots, rng)
    return -np.angle(X + 1j * Y)


def _rpe_overlap(psi0, unitary, *, cutoff, max_bond):
    r"""Return :math:`\bra{\psi_0} U \ket{\psi_0}` from a control-free simulation."""
    if isinstance(unitary, qtn.Gate):
        unitary = [unitary]
    # quimb copies psi0 into the circuit and returns another copy from circ.psi:
    # no explicit copy is needed and normalizing ket leaves the circuit intact
    circ = qtn.CircuitMPS(psi0=psi0, cutoff=cutoff, max_bond=max_bond)
    circ.apply_gates(unitary)
    # quimb never renormalizes a truncated MPS: the discarded weight is left out
    # of the state and used as its error estimate. Normalizing both states keeps
    # z a genuine expectation value, bounded by 1 and independent of the norm of
    # psi0, as measured by a Hadamard test on hardware.
    bra = psi0.copy()
    bra.normalize()
    ket = circ.psi
    ket.normalize()
    return bra.H @ ket


def _sample_hadamard(z_component, n_shots, rng):
    r"""Emulate ``n_shots`` Hadamard-test shots for an exact expectation value.

    The ancilla outcome is Bernoulli with :math:`P(1) = (1 - Z)/2`, so the
    number of ``1`` outcomes over ``n_shots`` shots is
    :math:`\mathrm{Binomial}(n_{\rm shots}, P(1))` and the estimated expectation
    is :math:`(n_{\rm shots} - 2\,\mathrm{popcount})/n_{\rm shots}`.
    """
    # both states are normalized, hence |z| <= 1 and p1 in [0, 1]; clip only
    # absorbs the rounding overshoot at |z| = 1, which rng.binomial rejects
    p1 = np.clip((1.0 - z_component) / 2.0, 0.0, 1.0)
    popcount = rng.binomial(n_shots, p1)
    return (n_shots - 2 * popcount) / n_shots


def angular_distance(phi, theta):
    """
    Compute the angular distance between two angles.

    The distance is defined modulo π and lies in the interval [0, π].

    Parameters
    ----------
    phi : float or array of float
        First angle in radians.
    theta : float or array of float
        Second angle in radians.

    Returns
    -------
    d : float or array of float
        Angular distance between ``phi`` and ``theta``.
    """
    K = np.rint((phi - theta) / (2 * np.pi))
    return np.abs(phi - theta - K * 2 * np.pi)


def rpe_update_theta(phi_m, theta_ref, m):
    r"""
    Refine the phase estimate at iteration ``m``.

    Parameters
    ----------
    phi_m : float
        Phase estimate at iteration ``m``, in radians.
    theta_ref : float
        Reference angle (previous phase estimate :math:`\theta_{m-1}`).
    m : int
        Iteration index.

    Returns
    -------
    theta_m : float
        Refined phase estimate, the candidate nearest to ``theta_ref``, wrapped
        into :math:`[-\pi, \pi)`.
    """
    # The candidates (phi_m + 2*pi*k) / 2^m form a uniform grid on the circle.
    # Grid point closest (modulo :math:`2\pi`) to ``theta_ref`` is obtained by rounding
    # the float (2^m theta_ref - phi_m) / 2pi
    k = round((2**m * theta_ref - phi_m) / (2 * np.pi))
    theta_m = (phi_m + 2 * np.pi * k) / 2**m
    return (theta_m + np.pi) % (2 * np.pi) - np.pi
